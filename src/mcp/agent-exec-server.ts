/**
 * The `agent-exec` MCP server: an owner-allowlisted command runner for the
 * worker's reproduce → fix → verify loop.
 *
 * The worker can already read, search and edit a project. It cannot run the
 * project's own tests, typecheck or lint, so a bug fix is written blind. This
 * server runs only the commands the owner wrote into `agent-exec.json`; the
 * model supplies a command name, never an argv. There is no shell.
 *
 * On macOS every command is wrapped by `/usr/bin/sandbox-exec` with a profile
 * generated from `src/authority/seatbelt.ts`: the workspace is the only write
 * root (plus temp and package caches), network is off, the kernel's protected
 * locations are denied, and `.git` stays read-only. Without a sandbox the
 * server refuses to run unless the config explicitly allows unsandboxed
 * execution.
 *
 * The file is self-contained (Node built-ins only) because the installer
 * copies it into the clone home. The declaration in `mcp.json` remains the
 * authority for the tool's risk; this module only executes.
 *
 * `agent-exec` MCP 服务器：所有者白名单式的命令执行器，为 Worker 的
 * “复现 → 修复 → 验证”回路服务。
 *
 * Worker 已经能读写、检索和编辑项目，却跑不了项目自己的测试、类型检查或 lint，所以修 Bug
 * 只能盲写。本服务器只运行所有者写进 `agent-exec.json` 的命令；模型只给命令名，永远不给
 * argv。这里没有 shell。
 *
 * 在 macOS 上，每条命令都由 `/usr/bin/sandbox-exec` 包裹，profile 由
 * `src/authority/seatbelt.ts` 生成：工作区是唯一写入根（外加临时目录与包缓存），网络关闭，
 * 内核的受保护位置被拒绝，`.git` 保持只读。没有沙箱时，除非配置显式允许无沙箱执行，服务器
 * 拒绝运行。
 *
 * 本文件自包含（只用 Node 内建模块），因为安装器会把它复制到 clone home。`mcp.json` 中的
 * 声明仍是工具风险的权威；本模块只负责执行。
 */
import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, isAbsolute, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const SERVER_NAME = "agent-exec";
export const SERVER_VERSION = "1.0.0";
export const PROTOCOL_VERSION = "2025-06-18";
export const SANDBOX_EXEC = "/usr/bin/sandbox-exec";
export const DEFAULT_TIMEOUT_MS = 240_000;
export const MAX_TIMEOUT_MS = 600_000;
export const MAX_STREAM_BYTES = 50_000;

export interface AgentExecCommand {
  name: string;
  argv: string[];
  description?: string;
  /** Per-command timeout; absent means the server default. 每条命令的超时；缺省用服务器默认值。 */
  timeoutMs?: number;
}

export interface AgentExecConfig {
  workspace: string;
  commands: AgentExecCommand[];
  /** A file holding a Seatbelt profile, generated by the installer. 安装器生成的 Seatbelt profile 文件。 */
  sandboxProfile?: string;
  /** Only for a platform with no sandbox: an explicit owner opt-out. 仅用于没有沙箱的平台：所有者的显式放弃。 */
  allowUnsandboxed?: boolean;
}

export interface AgentExecConfigLoad {
  config?: AgentExecConfig;
  errors: string[];
}

export interface AgentToolDefinition {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
}

export interface ToolRunResult {
  text: string;
  isError?: boolean;
}

const COMMAND_NAME = /^[A-Za-z0-9][A-Za-z0-9:_-]*$/;

/**
 * Children in flight. The MCP client kills the server's process group when the
 * step ends; each command runs in its own group so a timeout can kill the whole
 * tree, so the server must forward its own termination to those groups.
 * 在途子进程。MCP 客户端在步骤结束时杀死服务器的进程组；每条命令在独立进程组中运行，以便
 * 超时能杀掉整棵树，因此服务器必须把自己的终止信号转发给这些进程组。
 */
const activeChildren = new Set<ChildProcess>();

/**
 * Parse and validate an owner-written config. Every bad entry is reported; the
 * server never guesses an argv or a workspace.
 * 解析并校验所有者撰写的配置。每个坏条目都会被报告；服务器从不猜 argv 或工作区。
 */
export function parseAgentExecConfig(raw: unknown, where = "agent-exec.json"): AgentExecConfigLoad {
  const errors: string[] = [];
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) {
    return { errors: [`${where} must be an object.`] };
  }
  const record = raw as Record<string, unknown>;
  const workspace = typeof record.workspace === "string" ? record.workspace.trim() : "";
  if (workspace.length === 0 || !isAbsolute(workspace)) {
    errors.push(`${where}: "workspace" must be an absolute path.`);
  }
  const commands: AgentExecCommand[] = [];
  const names = new Set<string>();
  if (!Array.isArray(record.commands)) {
    errors.push(`${where}: "commands" must be an array.`);
  } else {
    for (const [index, entry] of record.commands.entries()) {
      if (typeof entry !== "object" || entry === null || Array.isArray(entry)) {
        errors.push(`${where}: commands[${index}] must be an object.`);
        continue;
      }
      const command = entry as Record<string, unknown>;
      const name = typeof command.name === "string" ? command.name.trim() : "";
      if (!COMMAND_NAME.test(name)) {
        errors.push(`${where}: commands[${index}].name must match ${COMMAND_NAME}.`);
        continue;
      }
      if (names.has(name)) {
        errors.push(`${where}: duplicate command name "${name}".`);
        continue;
      }
      if (!Array.isArray(command.argv) || command.argv.length === 0) {
        errors.push(`${where}: command "${name}" needs a non-empty argv array.`);
        continue;
      }
      const argv: string[] = [];
      for (const item of command.argv) {
        if (typeof item !== "string" || item.length === 0 || /[\0\r\n]/.test(item)) {
          errors.push(`${where}: command "${name}" has an invalid argv entry.`);
          argv.length = 0;
          break;
        }
        argv.push(item);
      }
      if (argv.length === 0) continue;
      const timeoutMs = typeof command.timeoutMs === "number" && Number.isFinite(command.timeoutMs) && command.timeoutMs > 0
        ? Math.min(MAX_TIMEOUT_MS, Math.trunc(command.timeoutMs))
        : undefined;
      commands.push({
        name,
        argv,
        ...(typeof command.description === "string" ? { description: command.description } : {}),
        ...(timeoutMs === undefined ? {} : { timeoutMs }),
      });
      names.add(name);
    }
  }
  const sandboxProfile = typeof record.sandboxProfile === "string" && record.sandboxProfile.trim().length > 0
    ? record.sandboxProfile.trim()
    : undefined;
  if (sandboxProfile !== undefined && !isAbsolute(sandboxProfile)) {
    errors.push(`${where}: "sandboxProfile" must be an absolute path.`);
  }
  if (errors.length > 0) return { errors };
  return {
    config: {
      workspace: resolve(workspace),
      commands,
      ...(sandboxProfile === undefined ? {} : { sandboxProfile }),
      ...(record.allowUnsandboxed === true ? { allowUnsandboxed: true } : {}),
    },
    errors: [],
  };
}

export function loadAgentExecConfig(path: string): AgentExecConfigLoad {
  let source: string;
  try {
    source = readFileSync(path, "utf8");
  } catch (error) {
    return { errors: [`${path} could not be read: ${error instanceof Error ? error.message : String(error)}`] };
  }
  try {
    return parseAgentExecConfig(JSON.parse(source) as unknown, path);
  } catch (error) {
    return { errors: [`${path} is not valid JSON: ${error instanceof Error ? error.message : String(error)}`] };
  }
}

/**
 * The model-facing catalogue. The descriptions carry the argument shape because
 * clone-ai's MCP client deliberately does not load a server's schema.
 * 面向模型的目录。描述里带参数形状，因为 clone-ai 的 MCP 客户端刻意不加载服务器自己的 Schema。
 */
export function toolDefinitions(): AgentToolDefinition[] {
  return [
    {
      name: "list_commands",
      description:
        "List the owner-approved commands in this workspace: name, argv and description. "
        + "Call this before run_command. No arguments.",
      inputSchema: { type: "object", properties: {} },
    },
    {
      name: "run_command",
      description:
        "Run one owner-approved command and return exit code, duration, stdout and stderr. "
        + "Args: {\"name\": string}. The command runs without a shell, in a minimal environment, "
        + "inside the workspace sandbox: writes are confined to the workspace and temp, network is off, "
        + "protected locations and .git are read-only. A non-zero exit is returned with the output.",
      inputSchema: {
        type: "object",
        properties: { name: { type: "string", description: "The command name from list_commands." } },
        required: ["name"],
      },
    },
  ];
}

export async function runTool(name: string, args: Record<string, unknown>, load: AgentExecConfigLoad): Promise<ToolRunResult> {
  if (name === "list_commands") {
    if (load.config === undefined) return { text: `Error: ${load.errors.join(" ")}`, isError: true };
    return { text: JSON.stringify(load.config.commands.map((command) => ({
      name: command.name,
      argv: command.argv,
      ...(command.description === undefined ? {} : { description: command.description }),
    })), null, 2) };
  }
  if (name === "run_command") {
    if (load.config === undefined) return { text: `Error: ${load.errors.join(" ")}`, isError: true };
    const commandName = typeof args.name === "string" ? args.name.trim() : "";
    if (commandName.length === 0) return { text: "Error: name must be a non-empty string.", isError: true };
    const command = load.config.commands.find((entry) => entry.name === commandName);
    if (command === undefined) {
      const available = load.config.commands.map((entry) => entry.name).join(", ") || "(none)";
      return { text: `Error: no command named "${commandName}". Available: ${available}.`, isError: true };
    }
    return executeCommand(command, load.config);
  }
  return { text: `Unknown tool: ${name}`, isError: true };
}

async function executeCommand(command: AgentExecCommand, config: AgentExecConfig): Promise<ToolRunResult> {
  const wrapped = wrapCommand(command.argv, config);
  if ("error" in wrapped) return { text: `Error: ${wrapped.error}`, isError: true };
  const timeoutMs = command.timeoutMs ?? DEFAULT_TIMEOUT_MS;
  const startedAt = Date.now();
  const stdout = new TailBuffer(MAX_STREAM_BYTES);
  const stderr = new TailBuffer(MAX_STREAM_BYTES);
  let timedOut = false;
  let settled = false;
  let child: ChildProcess;
  try {
    child = spawn(wrapped.command, wrapped.args, {
      cwd: config.workspace,
      env: minimalEnvironment(),
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
      ...(process.platform === "win32" ? {} : { detached: true }),
    });
  } catch (error) {
    return { text: `Error: could not start ${command.argv[0]}: ${error instanceof Error ? error.message : String(error)}`, isError: true };
  }
  // The child's stdout/stderr are non-null because stdio requested pipes.
  // 子进程的 stdout/stderr 非空，因为 stdio 请求了管道。
  child.stdout?.setEncoding("utf8");
  child.stdout?.on("data", (chunk: string) => stdout.push(chunk));
  child.stderr?.setEncoding("utf8");
  child.stderr?.on("data", (chunk: string) => stderr.push(chunk));
  activeChildren.add(child);

  const outcome = await new Promise<{ code: number | null; signal: NodeJS.Signals | null; error?: Error }>((resolvePromise) => {
    const timer = setTimeout(() => {
      timedOut = true;
      killGroup(child);
    }, timeoutMs);
    child.once("error", (error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      activeChildren.delete(child);
      resolvePromise({ code: null, signal: null, error });
    });
    child.once("close", (code, signal) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      activeChildren.delete(child);
      resolvePromise({ code, signal });
    });
  });
  const durationMs = Date.now() - startedAt;
  const failed = timedOut || outcome.error !== undefined || outcome.code !== 0;
  const header = [
    `command: ${command.name} (${command.argv.join(" ")})`,
    `sandbox: ${wrapped.sandboxed ? "seatbelt" : "none"}`,
    `exit: ${outcome.error === undefined ? (outcome.code ?? `signal ${outcome.signal ?? "unknown"}`) : `error: ${outcome.error.message}`}`,
    `duration: ${(durationMs / 1000).toFixed(1)}s`,
    ...(timedOut ? [`timed out after ${timeoutMs} ms`] : []),
    ...(stdout.truncated || stderr.truncated ? ["output: truncated to the last 50 KB per stream"] : []),
  ].join("\n");
  return {
    text: `${header}\n--- stdout ---\n${stdout.text || "(empty)"}\n--- stderr ---\n${stderr.text || "(empty)"}`,
    ...(failed ? { isError: true } : {}),
  };
}

function wrapCommand(argv: readonly string[], config: AgentExecConfig): { command: string; args: string[]; sandboxed: boolean } | { error: string } {
  const sandboxedUnavailable = process.platform === "darwin" && !existsSync(SANDBOX_EXEC);
  if (process.platform === "darwin" && !sandboxedUnavailable && config.sandboxProfile !== undefined) {
    let profile: string;
    try {
      profile = readFileSync(config.sandboxProfile, "utf8");
    } catch (error) {
      return { error: `could not read the sandbox profile ${config.sandboxProfile}: ${error instanceof Error ? error.message : String(error)}` };
    }
    if (profile.trim().length === 0) return { error: `the sandbox profile ${config.sandboxProfile} is empty` };
    return { command: SANDBOX_EXEC, args: ["-p", profile, ...argv], sandboxed: true };
  }
  if (config.allowUnsandboxed === true) {
    return { command: argv[0]!, args: argv.slice(1), sandboxed: false };
  }
  return {
    error: process.platform === "darwin"
      ? `no sandbox is available (${SANDBOX_EXEC} missing or no sandboxProfile configured); refusing to run project code unsandboxed`
      : "this platform has no sandbox; set allowUnsandboxed true only if you accept running project code unsandboxed",
  };
}

function killGroup(child: ChildProcess): void {
  if (child.pid === undefined) {
    child.kill("SIGKILL");
    return;
  }
  try {
    if (process.platform === "win32") child.kill("SIGKILL");
    else process.kill(-child.pid, "SIGKILL");
  } catch {
    child.kill("SIGKILL");
  }
}

/** The environment a project command may inherit: no credentials, no model keys. 项目命令可继承的环境：没有凭据，没有模型密钥。 */
export function minimalEnvironment(): NodeJS.ProcessEnv {
  const pathParts = [dirname(process.execPath), process.env.PATH].filter((part): part is string => typeof part === "string" && part.length > 0);
  return {
    PATH: pathParts.join(process.platform === "win32" ? ";" : ":"),
    HOME: process.env.HOME ?? homedir(),
    ...(process.env.LANG === undefined ? {} : { LANG: process.env.LANG }),
    TMPDIR: process.env.TMPDIR ?? tmpdir(),
    ...(process.platform === "win32" && process.env.TEMP !== undefined ? { TEMP: process.env.TEMP } : {}),
    ...(process.platform === "win32" && process.env.SYSTEMROOT !== undefined ? { SYSTEMROOT: process.env.SYSTEMROOT } : {}),
    CI: "1",
  };
}

class TailBuffer {
  readonly #limit: number;
  #value = "";
  #truncated = false;
  constructor(limit: number) {
    this.#limit = limit;
  }
  push(chunk: string): void {
    this.#value += chunk;
    if (this.#value.length > this.#limit) {
      this.#value = this.#value.slice(-this.#limit);
      this.#truncated = true;
    }
  }
  get text(): string {
    return this.#value;
  }
  get truncated(): boolean {
    return this.#truncated;
  }
}

export interface JsonRpcRequest {
  jsonrpc?: string;
  id?: number | string | null;
  method?: string;
  params?: unknown;
}

export async function handleMessage(message: JsonRpcRequest, load: AgentExecConfigLoad): Promise<Record<string, unknown> | undefined> {
  if (message.id === undefined || message.id === null) return undefined;
  const id = message.id;
  if (message.method === "initialize") {
    return {
      jsonrpc: "2.0",
      id,
      result: {
        protocolVersion: PROTOCOL_VERSION,
        capabilities: { tools: {} },
        serverInfo: { name: SERVER_NAME, version: SERVER_VERSION },
      },
    };
  }
  if (message.method === "tools/list") {
    return {
      jsonrpc: "2.0",
      id,
      result: { tools: toolDefinitions().map((tool) => ({ name: tool.name, description: tool.description, inputSchema: tool.inputSchema })) },
    };
  }
  if (message.method === "tools/call") {
    const params = typeof message.params === "object" && message.params !== null ? message.params as { name?: unknown; arguments?: unknown } : {};
    const name = typeof params.name === "string" ? params.name : "";
    const args = typeof params.arguments === "object" && params.arguments !== null && !Array.isArray(params.arguments)
      ? params.arguments as Record<string, unknown>
      : {};
    const result = await runTool(name, args, load);
    return {
      jsonrpc: "2.0",
      id,
      result: {
        content: [{ type: "text", text: result.text }],
        ...(result.isError === true ? { isError: true } : {}),
      },
    };
  }
  return { jsonrpc: "2.0", id, error: { code: -32601, message: `Unknown method: ${message.method ?? "(none)"}` } };
}

/** Serve newline-delimited JSON-RPC on stdin/stdout until the parent closes stdin. 在 stdin/stdout 上提供换行分隔的 JSON-RPC，直到父进程关闭 stdin。 */
export function startServer(configPath: string): void {
  const load = loadAgentExecConfig(configPath);
  const shutdown = (): void => {
    for (const child of activeChildren) killGroup(child);
    activeChildren.clear();
    process.exit(0);
  };
  process.on("SIGTERM", shutdown);
  process.on("SIGINT", shutdown);
  process.stdin.on("end", shutdown);
  let buffer = "";
  let queue: Promise<void> = Promise.resolve();
  process.stdin.setEncoding("utf8");
  process.stdin.on("data", (chunk: string) => {
    buffer += chunk;
    for (;;) {
      const index = buffer.indexOf("\n");
      if (index === -1) break;
      const line = buffer.slice(0, index).trim();
      buffer = buffer.slice(index + 1);
      if (line.length === 0) continue;
      queue = queue.then(() => handleLine(line));
    }
  });
  process.stdin.on("error", () => process.exit(0));

  async function handleLine(line: string): Promise<void> {
    let message: JsonRpcRequest;
    try {
      message = JSON.parse(line) as JsonRpcRequest;
    } catch {
      process.stdout.write(`${JSON.stringify({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "Parse error" } })}\n`);
      return;
    }
    try {
      const reply = await handleMessage(message, load);
      if (reply !== undefined) process.stdout.write(`${JSON.stringify(reply)}\n`);
    } catch (error) {
      process.stdout.write(`${JSON.stringify({
        jsonrpc: "2.0",
        id: message.id ?? null,
        error: { code: -32603, message: error instanceof Error ? error.message : String(error) },
      })}\n`);
    }
  }
}

/** The `--config` value, or undefined. `--config` 的值；缺失时返回 undefined。 */
export function configPathFromArgs(argv: readonly string[]): string | undefined {
  const index = argv.indexOf("--config");
  if (index < 0) return undefined;
  const value = argv[index + 1];
  return value === undefined || value.trim().length === 0 ? undefined : value.trim();
}

const invokedDirectly = process.argv[1] !== undefined
  && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (invokedDirectly) {
  const configPath = configPathFromArgs(process.argv.slice(2));
  if (configPath === undefined) {
    process.stderr.write("agent-exec needs --config <path>.\n");
    process.exit(2);
  }
  startServer(configPath);
}
